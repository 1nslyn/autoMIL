"""Validate TITAN slide-level features and detect the true embedding dimension.

TITAN *is* the encoder: each slide has exactly one frozen embedding vector
in ``features_titan/<slide_id>.h5`` (no bag, no patches). This module never
hard-codes the embedding dimension -- it is read from the first available
feature file and returned to the caller, mirroring
``nnmil/prepare.py::_analyze_features``'s fail-fast-if-missing behavior
(design spec §7, §13.2 correction "TITAN is 768-d").

We reuse the SAME split CSVs generated by ``pipeline/splits.py`` -- this
module only validates that a slide-feature file exists for every slide
referenced in the task CSV; it does not regenerate splits.
"""

from __future__ import annotations

import json
import os

import h5py
import pandas as pd

# Dataset keys TITAN slide-feature files may use for the embedding vector.
# TRIDENT's slide encoder emits "features" for most encoders; TITAN's own
# extraction path uses "slide_feature" for the pooled slide-level vector.
# We accept either so the arm isn't brittle to a naming choice made at
# extraction time.
_FEATURE_KEYS = ("slide_feature", "features", "feature")


def _read_slide_embedding_dim(h5_path: str) -> int:
    """Read the embedding dimension from a single slide-feature H5 file.

    Accepts stored shapes ``[D]`` or ``[1, D]`` (a leading singleton batch
    dim, as commonly emitted by slide encoders) and returns ``D``.
    """
    with h5py.File(h5_path, "r") as f:
        key = next((k for k in _FEATURE_KEYS if k in f), None)
        if key is None:
            raise ValueError(
                f"Slide feature file {h5_path} has no recognized dataset "
                f"key (looked for {_FEATURE_KEYS!r}, found {list(f.keys())!r})."
            )
        shape = f[key].shape

    if len(shape) == 1:
        return int(shape[0])
    if len(shape) == 2 and shape[0] == 1:
        return int(shape[1])
    raise ValueError(
        f"Slide feature file {h5_path} has unexpected shape {shape!r}; "
        "expected a single embedding vector shaped [D] or [1, D]."
    )


def validate_titan_features(
    task_csv: str,
    features_dir: str,
) -> int:
    """Validate a slide feature exists for every slide in *task_csv*.

    Returns the detected embedding dimension (read from the first
    available feature file -- never hard-coded).

    Raises ``FileNotFoundError`` if any slide referenced in the task CSV
    is missing its feature file, mirroring ``nnmil/prepare.py``'s
    fail-fast-if-missing behavior: a silently-filtered TITAN grid would
    train on however many slides happen to have features, without the
    operator ever noticing.
    """
    task_df = pd.read_csv(task_csv)
    slide_ids = task_df["slide_id"].tolist()

    missing: list[str] = []
    embed_dim: int | None = None
    for sid in slide_ids:
        h5_path = os.path.join(features_dir, f"{sid}.h5")
        if not os.path.exists(h5_path):
            missing.append(sid)
            continue
        if embed_dim is None:
            embed_dim = _read_slide_embedding_dim(h5_path)

    if missing:
        preview = ", ".join(missing[:5])
        suffix = f" ... +{len(missing) - 5}" if len(missing) > 5 else ""
        raise FileNotFoundError(
            f"Missing TITAN slide features for {len(missing)}/{len(slide_ids)} "
            f"slides in {task_csv} (dir: {features_dir}): {preview}{suffix}. "
            "Run TITAN slide-feature extraction before benchmarking this arm."
        )

    if embed_dim is None:
        # task_df was empty -- nothing to validate against.
        raise FileNotFoundError(
            f"Task CSV {task_csv} has no slide_id rows; cannot detect the "
            f"TITAN embedding dimension from {features_dir}."
        )

    return embed_dim


def prepare_titan_experiment(
    benchmark_dir: str,
    task_name: str,
    features_base_dir: str,
) -> dict:
    """Validate TITAN features for one task and write a tiny manifest.

    Returns the manifest dict (also written to
    ``<benchmark_dir>/titan/<task_name>/manifest.json``) so callers can
    read the detected ``embed_dim`` without re-parsing the H5 files.

    The manifest is intentionally tiny: TITAN has no bag/patch structure
    to plan around, so unlike nnMIL's ``dataset_plan.json`` there is
    nothing else to precompute. The manifest exists only as a cached,
    idempotent record of the detected dimension and validated slide count.
    """
    task_csv = os.path.join(benchmark_dir, "dataset_csv", f"{task_name}.csv")
    features_dir = os.path.join(features_base_dir, "features_titan")

    embed_dim = validate_titan_features(task_csv, features_dir)

    task_df = pd.read_csv(task_csv)
    manifest = {
        "task": task_name,
        "features_dir": features_dir,
        "embed_dim": embed_dim,
        "n_slides": len(task_df),
    }

    manifest_dir = os.path.join(benchmark_dir, "titan", task_name)
    os.makedirs(manifest_dir, exist_ok=True)
    manifest_path = os.path.join(manifest_dir, "manifest.json")
    with open(manifest_path, "w") as f:
        json.dump(manifest, f, indent=2)

    return manifest
